package thaumcraft.common.blocks.basic;

import net.minecraft.core.BlockPos;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.EntityBlock;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityTicker;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockState;
import thaumcraft.api.aspects.Aspect;
import thaumcraft.common.tiles.TileNode;
import thaumcraft.init.ModBlockEntities;
import thaumcraft.init.ModItems;

/**
 * Charged Obsidian Totem (TC4 blockCosmeticSolid meta 8).
 * A totem pillar segment hosting an aura node TileEntity (dark/sinister node
 * when generated by worldgen). TC4 behaviour:
 * - breaking it drops Wisp Essence for the stored aspects (amount/10 per aspect)
 * - it drops a regular Obsidian Totem item (TC4 damageDropped 8 -> 1)
 */
public class BlockChargedObsidianTotem extends BlockObsidianTotem implements EntityBlock {

    public BlockChargedObsidianTotem() {
        super(props());
    }

    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new TileNode(pos, state);
    }

    @Override
    public <T extends BlockEntity> BlockEntityTicker<T> getTicker(Level level, BlockState state, BlockEntityType<T> type) {
        if (type == ModBlockEntities.NODE.get()) {
            if (level.isClientSide) {
                return (lvl, pos, st, be) -> TileNode.clientTick(lvl, pos, st, (TileNode) be);
            }
            return (lvl, pos, st, be) -> TileNode.serverTick(lvl, pos, st, (TileNode) be);
        }
        return null;
    }

    @Override
    public BlockState playerWillDestroy(Level level, BlockPos pos, BlockState state, Player player) {
        if (!level.isClientSide && level.getBlockEntity(pos) instanceof TileNode node) {
            // TC4: essence per 10 vis of each aspect (minimum 5 vis yields one)
            for (Aspect aspect : node.getAspects().getAspects()) {
                int amount = node.getAspects().getAmount(aspect);
                if (amount >= 5) {
                    int drops = amount / 10;
                    if (drops <= 0) {
                        drops = 1;
                    }
                    // TC4: each drop carries 2 points of the aspect
                    for (int a = 0; a < drops; a++) {
                        ItemStack stack = thaumcraft.common.items.resources.ItemWispEssence.createStack(
                                ModItems.WISP_ESSENCE.get(), aspect, 2);
                        popResource(level, pos, stack);
                    }
                }
            }
        }
        return super.playerWillDestroy(level, pos, state, player);
    }
}
