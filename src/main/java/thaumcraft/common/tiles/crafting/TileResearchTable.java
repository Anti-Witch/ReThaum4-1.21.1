/**
 * TileResearchTable - The TC4-style research table tile entity.
 *
 * Slots:
 * - 0: Scribing tools (IScribeTools)
 * - 1: Research notes (ItemResearchNotes)
 *
 * The table is used for the TC4 hex-grid research minigame: the player places
 * aspects from their research pool onto the note's hex canvas (via
 * placeAspect), combines aspects on the linking block (via combineAspects),
 * gains bonus aspects from the surrounding area (via recalculateBonus) and
 * can duplicate completed notes (via duplicate).
 *
 * Ported from OpenTC4 TileResearchTable (TC4) - hex-grid mechanic is TC4-only,
 * not present in TC6/ref. Adapted to the 1.21.1 target: knowledge is stored on
 * the player capability (research pool) instead of TC4's player knowledge map,
 * and note completion is an NBT flag (ResearchNotes) instead of damage 64.
 *
 * @author Azanor
 */
public class TileResearchTable extends TileThaumcraftInventory implements MenuProvider {

    public static final int SLOT_SCRIBING_TOOLS = 0;
    public static final int SLOT_NOTE = 1;

    /** Aspects generated by the environment (recalculateBonus) - free to use */
    public AspectList bonusAspects = new AspectList();
    /** Runtime hex-grid data of the research note in slot 1 (null if absent) */
    public ResearchNoteData data = null;
    /** Tick counter used to periodically recompute bonus aspects */
    private int nextRecalc = 0;

    public TileResearchTable(BlockPos pos, BlockState state) {
        super(ModBlockEntities.RESEARCH_TABLE.get(), pos, state, 2);
        this.syncedSlots = new int[] { 0, 1 };
    }

    // ==================== Tick ====================

    public static void serverTick(Level level, BlockPos pos, BlockState state, TileResearchTable tile) {
        tile.tickServer();
    }

    private void tickServer() {
        if (level == null || level.isClientSide) return;
        if (nextRecalc++ > 600) {
            nextRecalc = 0;
            recalculateBonus();
            syncTile(false);
            setChanged();
        }
    }

    // ==================== MenuProvider ====================

    @Override
    public Component getDisplayName() {
        return Component.translatable("block.thaumcraft.research_table");
    }

    @Nullable
    @Override
    public AbstractContainerMenu createMenu(int containerId, Inventory playerInventory, Player player) {
        return new ResearchTableMenu(containerId, playerInventory, this);
    }

    // ==================== NBT ====================

    @Override
    protected void writeSyncNBT(CompoundTag tag) {
        super.writeSyncNBT(tag);
        tag.putInt("nextRecalc", nextRecalc);
        ListTag bonusTag = new ListTag();
        for (Aspect aspect : bonusAspects.getAspects()) {
            if (aspect != null && bonusAspects.getAmount(aspect) > 0) {
                CompoundTag t = new CompoundTag();
                t.putString("tag", aspect.getTag());
                bonusTag.add(t);
            }
        }
        tag.put("bonusAspects", bonusTag);
    }

    @Override
    protected void readSyncNBT(CompoundTag tag) {
        super.readSyncNBT(tag);
        nextRecalc = tag.getInt("nextRecalc");
        bonusAspects = new AspectList();
        ListTag bonusTag = tag.getList("bonusAspects", Tag.TAG_COMPOUND);
        for (int x = 0; x < bonusTag.size(); x++) {
            String s = bonusTag.getCompound(x).getString("tag");
            Aspect aspect = Aspect.getAspect(s);
            if (aspect != null) {
                bonusAspects.merge(aspect, 1);
            }
        }
    }

    // ==================== Note Data ====================

    /**
     * Refresh the runtime note data from the research note in slot 1.
     */
    public void gatherResults() {
        data = null;
        ItemStack note = getItem(SLOT_NOTE);
        if (note != null && !note.isEmpty() && note.getItem() instanceof ItemResearchNotes) {
            data = ResearchNotes.getData(note);
        }
    }

    /**
     * Try to place (or remove, when aspect is null) an aspect on a hex of the note's
     * canvas. Consumes ink from the scribing tools, removes/adds the aspect from/to
     * the player's research pool and checks for note completion.
     * Verbatim port of OpenTC4 TileResearchTable.placeAspect (TC4).
     */
    public void placeAspect(int q, int r, Aspect aspect, Player player) {
        if (data == null) {
            gatherResults();
        }

        ItemStack tools = getItem(SLOT_SCRIBING_TOOLS);
        ItemStack note = getItem(SLOT_NOTE);

        if (!ResearchNotes.consumeInkFromTable(tools, false)) return;
        if (note.isEmpty() || !(note.getItem() instanceof ItemResearchNotes) || data == null || data.isComplete()) return;

        // TC4 bonus researches (which are not present in this port - both return false)
        boolean r1 = false;
        boolean r2 = false;
        IPlayerKnowledge knowledge = ThaumcraftCapabilities.getKnowledge(player);
        if (knowledge == null) {
            return;
        }
        r1 = knowledge.isResearchComplete("RESEARCHER1");
        r2 = knowledge.isResearchComplete("RESEARCHER2");

        HexUtils.Hex hex = new HexUtils.Hex(q, r);
        ResearchNotes.HexEntry he;
        if (aspect != null) {
            he = new ResearchNotes.HexEntry(aspect, 2);
            if (r2 && level.random.nextFloat() < 0.1F) {
                // RESEARCHER2: 10% chance to place for free
                level.playSound(null, player.getX(), player.getY(), player.getZ(),
                        SoundEvents.EXPERIENCE_ORB_PICKUP, SoundSource.PLAYERS, 0.2F, 0.9F + level.random.nextFloat() * 0.2F);
            } else if (knowledge.getResearchPool().getAmount(aspect) <= 0) {
                // No aspect in the pool: pull it from the table's bonus aspects
                this.bonusAspects.remove(aspect, 1);
                syncTile(false);
                setChanged();
            } else {
                // Consume the aspect from the player's research pool
                knowledge.addAspectsToResearchPool(aspect, -1);
                if (player instanceof ServerPlayer serverPlayer) {
                    knowledge.sync(serverPlayer);
                }
            }
        } else {
            // Erasing an aspect - chance to refund it to the pool (RESEARCHER1/2 bonuses)
            float f = level.random.nextFloat();
            ResearchNotes.HexEntry existing = data.hexEntries.get(hex.toString());
            if (existing != null && existing.aspect != null && (r1 && f < 0.25F || r2 && f < 0.5F)) {
                level.playSound(null, player.getX(), player.getY(), player.getZ(),
                        SoundEvents.EXPERIENCE_ORB_PICKUP, SoundSource.PLAYERS, 0.2F, 0.9F + level.random.nextFloat() * 0.2F);
                knowledge.addAspectsToResearchPool(existing.aspect, 1);
                if (player instanceof ServerPlayer serverPlayer) {
                    knowledge.sync(serverPlayer);
                }
            }
            he = new ResearchNotes.HexEntry(null, 0);
        }

        data.hexEntries.put(hex.toString(), he);
        data.hexes.put(hex.toString(), hex);
        ResearchNotes.updateData(note, data);
        ResearchNotes.consumeInkFromTable(tools, true);

        if (!level.isClientSide && ResearchNotes.checkResearchCompletion(note, data, player)) {
            level.blockEvent(worldPosition, getBlockState().getBlock(), 1, 1);
        }

        syncTile(false);
        setChanged();
    }

    /**
     * Combine two aspects on the linking block. If the combination yields a
     * compound aspect it is discovered (added to the player's research pool).
     * The used aspects are removed from the pool (or from the table's bonus
     * aspects when ab1/ab2 are set).
     * Ported from OpenTC4 PacketAspectCombinationToServer.onMessage (TC4).
     */
    public void combineAspects(Aspect aspect1, Aspect aspect2, boolean ab1, boolean ab2, Player player) {
        if (aspect1 == null || aspect2 == null) return;
        IPlayerKnowledge knowledge = ThaumcraftCapabilities.getKnowledge(player);
        if (knowledge == null) return;

        Aspect combo = ResearchManager.getCombinationResult(aspect1, aspect2);
        int pool1 = knowledge.getResearchPool().getAmount(aspect1);
        int pool2 = knowledge.getResearchPool().getAmount(aspect2);

        // Sanity check: both aspects must be available (pool or bonus)
        if ((pool1 > 0 || ab1) && (pool2 > 0 || ab2)) {
            if (pool1 <= 0 && ab1) {
                bonusAspects.remove(aspect1, 1);
                syncTile(false);
                setChanged();
            } else {
                knowledge.addAspectsToResearchPool(aspect1, -1);
                if (player instanceof ServerPlayer serverPlayer) {
                    knowledge.sync(serverPlayer);
                }
            }

            if (pool2 <= 0 && ab2) {
                bonusAspects.remove(aspect2, 1);
                syncTile(false);
                setChanged();
            } else {
                knowledge.addAspectsToResearchPool(aspect2, -1);
                if (player instanceof ServerPlayer serverPlayer) {
                    knowledge.sync(serverPlayer);
                }
            }

            if (combo != null) {
                // Discover the new aspect (TC4's checkAndSyncAspectKnowledge):
                // first discovery marks the aspect as known and grants a +2 bonus.
                int comboAmount = 1;
                if (!knowledge.hasDiscoveredAspect(combo)) {
                    knowledge.addDiscoveredAspect(combo);
                    comboAmount += 2;
                }
                knowledge.addAspectsToResearchPool(combo, comboAmount);
                if (player instanceof ServerPlayer serverPlayer) {
                    knowledge.sync(serverPlayer);
                }
            }
        }
    }

    // ==================== Duplicate Note ====================

    /**
     * Duplicate the completed research note in slot 1 (paper + ink sac consumed
     * from the player's inventory, required aspects re-spent from the pool).
     * Verbatim port of OpenTC4 TileResearchTable.duplicate (TC4).
     */
    public void duplicate(Player player) {
        if (data == null) {
            gatherResults();
        }
        // NOTE: data can still be null (note without hex data) - TC4 checks this
        // before touching the note.
        if (data == null) {
            return;
        }

        ItemStack note = getItem(SLOT_NOTE);
        if (note.isEmpty() || !(note.getItem() instanceof ItemResearchNotes)) return;

        boolean hasPaper = false;
        int paperSlot = -1;
        boolean hasInk = false;
        int inkSlot = -1;
        for (int a = 0; a < player.getInventory().getContainerSize(); a++) {
            ItemStack is = player.getInventory().getItem(a);
            if (is != null && !is.isEmpty()) {
                if (is.is(Items.PAPER) && !hasPaper) {
                    hasPaper = true;
                    paperSlot = a;
                }
                if (is.is(Items.INK_SAC) && !hasInk) {
                    hasInk = true;
                    inkSlot = a;
                }
            }
        }

        if (data != null && data.isComplete() && hasPaper && hasInk) {
            ResearchEntry rr = ResearchCategories.getResearch(data.key);
            if (rr == null || rr.getRequiredAspects() == null) return;

            IPlayerKnowledge knowledge = ThaumcraftCapabilities.getKnowledge(player);
            if (knowledge == null) return;

            // Cost check: required aspects + copies so far
            for (Aspect aspect : rr.getRequiredAspects().getAspects()) {
                if (knowledge.getResearchPool().getAmount(aspect) < rr.getRequiredAspects().getAmount(aspect) + data.copies) {
                    return;
                }
            }

            for (Aspect aspect : rr.getRequiredAspects().getAspects()) {
                knowledge.addAspectsToResearchPool(aspect, -(rr.getRequiredAspects().getAmount(aspect) + data.copies));
            }
            if (player instanceof ServerPlayer serverPlayer) {
                knowledge.sync(serverPlayer);
            }

            // Consume paper and ink
            player.getInventory().removeItem(paperSlot, 1);
            player.getInventory().removeItem(inkSlot, 1);

            if (level != null) {
                level.blockEvent(worldPosition, getBlockState().getBlock(), 1, 1);
            }

            data.copies++;
            ResearchNotes.updateData(note, data);
            note.grow(1);
            syncTile(false);
            setChanged();
        }
    }

    // ==================== Bonus Aspects ====================

    /**
     * Recalculate the table's free bonus aspects based on the surrounding area.
     * Verbatim port of OpenTC4 TileResearchTable.recalculateBonus (TC4),
     * adapted to the 1.21.1 target: Thaumcraft-specific worldgen blocks
     * (blockCustomOre, blockCrystal, blockJar) are not present in this port,
     * so only the vanilla-environment and location-based checks remain.
     */
    private void recalculateBonus() {
        if (level == null) return;

        // Night time in a dark, enclosed space -> Entropy
        if (!level.isDay() && level.getRawBrightness(worldPosition.above(), 0) < 4 && !level.canSeeSky(worldPosition.above())
                && level.random.nextInt(20) == 0) {
            bonusAspects.merge(Aspect.ENTROPY, 1);
        }
        if ((float) worldPosition.getY() > (float) level.getHeight() * 0.5F && level.random.nextInt(20) == 0) {
            bonusAspects.merge(Aspect.AIR, 1);
        }
        if ((float) worldPosition.getY() > (float) level.getHeight() * 0.66F && level.random.nextInt(20) == 0) {
            bonusAspects.merge(Aspect.AIR, 1);
        }
        if ((float) worldPosition.getY() > (float) level.getHeight() * 0.75F && level.random.nextInt(20) == 0) {
            bonusAspects.merge(Aspect.AIR, 1);
        }

        for (int x = -8; x <= 8; x++) {
            for (int z = -8; z <= 8; z++) {
                for (int y = -8; y <= 8; y++) {
                    BlockPos check = worldPosition.offset(x, y, z);
                    if (check.getY() <= 0 || check.getY() >= level.getHeight()) continue;

                    BlockState bs = level.getBlockState(check);
                    if (bs.getBlock() == Blocks.FIRE || bs.getBlock() == Blocks.LAVA
                            || bs.getBlock() == Blocks.CAMPFIRE || bs.getBlock() == Blocks.SOUL_CAMPFIRE) {
                        // Fire -> Fire aspect
                        if (bonusAspects.getAmount(Aspect.FIRE) < 1 && level.random.nextInt(20) == 0) {
                            bonusAspects.merge(Aspect.FIRE, 1);
                            return;
                        }
                    } else if (bs.getBlock() == Blocks.GRASS_BLOCK || bs.getBlock() == Blocks.DIRT
                            || bs.getBlock() == Blocks.MYCELIUM || bs.getBlock() == Blocks.PODZOL
                            || bs.getBlock() == Blocks.SAND || bs.getBlock() == Blocks.GRAVEL) {
                        // Ground -> Earth aspect
                        if (bonusAspects.getAmount(Aspect.EARTH) < 1 && level.random.nextInt(20) == 0) {
                            bonusAspects.merge(Aspect.EARTH, 1);
                            return;
                        }
                    } else if (bs.getBlock() == Blocks.WATER) {
                        // Water -> Water aspect
                        if (bonusAspects.getAmount(Aspect.WATER) < 1 && level.random.nextInt(15) == 0) {
                            bonusAspects.merge(Aspect.WATER, 1);
                            return;
                        }
                    } else if (bs.getBlock() == Blocks.REDSTONE_WIRE || bs.getBlock() == Blocks.REDSTONE_BLOCK
                            || bs.getBlock() == Blocks.PISTON || bs.getBlock() == Blocks.STICKY_PISTON) {
                        // Redstone circuits -> Order aspect
                        if (bonusAspects.getAmount(Aspect.ORDER) < 1 && level.random.nextInt(20) == 0) {
                            bonusAspects.merge(Aspect.ORDER, 1);
                            return;
                        }
                    } else if (bs.getBlock() == Blocks.IRON_ORE || bs.getBlock() == Blocks.DEEPSLATE_IRON_ORE
                            || bs.getBlock() == Blocks.GOLD_ORE || bs.getBlock() == Blocks.DEEPSLATE_GOLD_ORE
                            || bs.getBlock() == Blocks.NETHERITE_BLOCK || bs.getBlock() == Blocks.ANVIL) {
                        // Metal -> Metallum aspect
                        if (bonusAspects.getAmount(Aspect.METAL) < 1 && level.random.nextInt(20) == 0) {
                            bonusAspects.merge(Aspect.METAL, 1);
                            return;
                        }
                    }

                    if (bs.getBlock() == Blocks.BOOKSHELF && level.random.nextInt(300) == 0) {
                        Aspect[] aspects = Aspect.aspects.values().toArray(new Aspect[0]);
                        if (aspects.length > 0) {
                            bonusAspects.merge(aspects[level.random.nextInt(aspects.length)], 1);
                            return;
                        }
                    }
                }
            }
        }
    }

    // ==================== Container Validation ====================

    @Override
    public boolean canPlaceItem(int slot, ItemStack stack) {
        if (stack == null || stack.isEmpty()) return false;
        if (slot == SLOT_SCRIBING_TOOLS) {
            return stack.getItem() instanceof IScribeTools;
        }
        if (slot == SLOT_NOTE) {
            return stack.getItem() == ModItems.RESEARCH_NOTES.get() || stack.getItem() instanceof ItemResearchNotes;
        }
        return false;
    }

    // ==================== Block Events ====================

    @Override
    public boolean triggerEvent(int id, int param) {
        if (id == 1) {
            if (level != null && level.isClientSide) {
                level.playLocalSound(
                        worldPosition.getX() + 0.5, worldPosition.getY() + 0.5, worldPosition.getZ() + 0.5,
                        ModSounds.LEARN.get(), SoundSource.BLOCKS, 1.0f, 1.0f, false
                );
            }
            return true;
        }
        return super.triggerEvent(id, param);
    }
}